// Generates the reference pages in docs/ from the code, so they can't drift:
// docs/checks.md (every check of every provider) and docs/permissions.md (every
// data source and the permission, role or IAM action that grants it). `npm run docs` writes
// them; a test fails when they're out of date.

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { CATEGORIES, CHECKS, type CheckDef } from "../src/providers/catalog.ts";
import { SOURCES, SOURCE_KEYS } from "../src/core/sources.ts";
import { VERCEL_SOURCES, VERCEL_SOURCE_KEYS } from "../src/providers/vercel/sources.ts";
import { AWS_SOURCES, AWS_SOURCE_KEYS } from "../src/providers/aws/sources.ts";
import { PROVIDERS, PROVIDER_INFO, providerOfUrl, type ProviderId } from "../src/shared/providers.ts";
import { SEVERITY_LABEL } from "../src/shared/severity.ts";

const HEADER = "<!-- Generated by `npm run docs` from the check modules. Edit those, not this file. -->";
const anchor = (s: string) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9 -]/g, "")
    .trim()
    .replace(/ /g, "-");

/** "1. … 2. …" becomes a numbered list, as in the dashboard. */
function steps(text: string): string {
  const parts = text
    .split(/\s*(?:^|\n|\s)(?=\d+\.\s)/)
    .map((s) => s.replace(/^\d+\.\s*/, "").trim())
    .filter(Boolean);
  return parts.length < 2 ? text : parts.map((s, i) => `${i + 1}. ${s}`).join("\n");
}

/** Each provider's source registry. A new provider doesn't compile until it is listed here. */
const SOURCE_REGISTRY: Record<ProviderId, Record<string, { label: string }>> = { cloudflare: SOURCES, vercel: VERCEL_SOURCES, aws: AWS_SOURCES };
const sourceLabel = (c: CheckDef, k: string) => SOURCE_REGISTRY[c.provider][k].label;
/** A check links its own provider's docs; one that spans providers may link the other's. */
const docsLabel = (c: CheckDef) => `${PROVIDER_INFO[providerOfUrl(c.docs!) ?? c.provider].label} docs`;

function check(c: CheckDef): string {
  const reads = (c.requires ?? []).map((k) => sourceLabel(c, k));
  const facts = [
    `**Severity:** ${SEVERITY_LABEL[c.severity]}`,
    c.attackPath ? "**Attack path**" : null,
    c.id.startsWith("XP-") ? "**Spans providers**" : null,
    reads.length ? `**Reads:** ${reads.join(", ")}` : null,
    c.docs ? `[${docsLabel(c)}](${c.docs})` : null,
  ].filter(Boolean);
  return [`#### ${c.id}: ${c.title}`, "", facts.join(" · "), "", c.why, "", "**How to fix**", "", steps(c.fix), ""].join("\n");
}

export function checksDoc(): string {
  const groups = PROVIDERS.map((p) => ({
    p,
    label: PROVIDER_INFO[p].label,
    by: CATEGORIES.map((cat) => ({ cat, list: CHECKS.filter((c) => c.provider === p && c.category === cat) })).filter((g) => g.list.length),
  }));
  return [
    HEADER,
    "",
    "# Checks",
    "",
    "Keelson runs its own checks on every provider, and imports Cloudflare Security Center insights alongside them.",
    "A check evaluates every resource it applies to (an account, zone, project, bucket, hostname, rule, token…) as pass or fail;",
    "each failure is a finding. Severity is the check's default, and a finding can raise or lower it",
    "(for example, a public R2 bucket is critical when it holds backups). Checks marked **Attack path** describe a concrete way in",
    "and are shown first on the Overview. When the token can't read a source a check needs, the check is skipped, never passed.",
    "",
    "Checks marked **Spans providers** (XP-) compare an account with the other accounts in its entity, for example Cloudflare or Route 53",
    "DNS records with the domains of the entity's Vercel projects, or with the endpoints its AWS accounts have. They read the latest scan",
    "of those accounts, and are skipped when the entity has no scanned account on the other provider.",
    "",
    "| Provider | Category | Checks |",
    "|---|---|---|",
    ...groups.flatMap((g) => g.by.map((x) => `| ${g.label} | [${x.cat}](#${anchor(`${g.label} ${x.cat}`)}) | ${x.list.length} |`)),
    "",
    ...groups.flatMap((g) => [`## ${g.label}`, "", ...g.by.flatMap((x) => [`### ${g.label}: ${x.cat}`, "", ...x.list.map(check)])]),
  ].join("\n");
}

/** What reads a source when no single check depends on it. */
const OTHER_USES: Record<string, string> = {
  zones: "Every zone-level check",
  subscriptions: "Plan detection and the Value page",
  securityCenter: "Imported Security Center insights",
};

export function permissionsDoc(): string {
  const needs = (k: string, provider = "cloudflare") => CHECKS.filter((c) => c.provider === provider && c.requires?.includes(k)).map((c) => c.id);
  const awsRows = AWS_SOURCE_KEYS.map((k) => {
    const s = AWS_SOURCES[k];
    const ids = needs(k, "aws");
    return `| ${s.label}${s.regional ? " (every enabled region)" : ""} | ${s.permission
      .split(", ")
      .map((a) => `\`${a}\``)
      .join(", ")} | ${ids.length ? ids.join(", ") : "Supporting data for other checks"} |`;
  });
  const vercelRows = VERCEL_SOURCE_KEYS.map((k) => {
    const s = VERCEL_SOURCES[k];
    const ids = needs(k, "vercel");
    return `| ${s.label} | ${s.permission} | ${ids.length ? ids.join(", ") : "Supporting data for other checks"} |`;
  });
  const rows = SOURCE_KEYS.filter((k) => !SOURCES[k].external).map((k) => {
    const s = SOURCES[k];
    const ids = needs(k);
    return `| ${s.label}${s.graphql ? " (GraphQL)" : ""} | ${s.permission} | ${ids.length ? ids.join(", ") : (OTHER_USES[k] ?? "Supporting data for other checks")} |`;
  });
  const external = SOURCE_KEYS.filter((k) => SOURCES[k].external).map((k) => `- ${SOURCES[k].label}`);
  return [
    HEADER,
    "",
    "# Permissions",
    "",
    "Keelson only reads, on every provider. Each provider's section lists the data a scan reads and what grants it:",
    "a token permission on Cloudflare, a team role on Vercel, IAM actions on AWS.",
    "",
    "## Cloudflare",
    "",
    "The simplest token is Cloudflare's **Read all resources** template, which covers almost everything below.",
    "Two sources need more:",
    "",
    "- **Account API tokens** need *Account API Tokens Read*, which the template doesn't include.",
    "- **Logpush jobs** can only be listed with a write permission, so Keelson doesn't list them; it reads Logpush health from GraphQL analytics instead.",
    "",
    "A source the token can't read shows up under **Scans → Data coverage** with the permission it needs, and the checks that depend on it are",
    "skipped rather than passed. The setup screen tests a token against each source before you connect it.",
    "",
    "| Source | Permission | Checks that read it |",
    "|---|---|---|",
    ...rows,
    "",
    "These sources aren't Cloudflare API reads and need no permission:",
    "",
    ...external,
    "",
    "## Vercel",
    "",
    "Vercel access tokens can't be limited to reading: a token can do whatever its user's role allows on each team it reaches.",
    "Keelson only ever sends GET requests to Vercel (`test/vercel.test.ts` fails on anything else), and never asks for environment",
    "variable values. A token created by a member with the **Viewer** role reads almost everything below; environment variable names,",
    "the firewall configuration, drains and webhooks need a role that can see them. Create the token under **Account Settings → Tokens**,",
    "scoped to the team you want to scan (or Full Account for every team), with an expiration date.",
    "",
    "| Source | Who can read it | Checks that read it |",
    "|---|---|---|",
    ...vercelRows,
    "",
    "## AWS",
    "",
    "An access key belongs to one AWS account, so each account needs its own. In each account, create an IAM user for Keelson,",
    "attach AWS's managed **SecurityAudit** policy, and create an access key under **IAM → Users → the user → Security credentials**.",
    "SecurityAudit reads configuration only: it can't change anything, and it can't read the objects in your buckets or the rows in your",
    "databases. Temporary keys (the ones that start with ASIA) aren't accepted, because they expire within hours.",
    "",
    "Keelson signs every request itself and only ever sends GET requests to AWS (`test/aws.test.ts` fails on anything else). Services",
    "that can only be read with POST requests, such as CloudTrail, KMS and Config, aren't read yet. It never stores a policy document, a",
    "Lambda environment variable or an instance's start-up script (the script is scanned for credentials in memory, and only the kind found",
    "is kept), and keeps only the last four characters of an access key ID. To recognise DNS records that point at AWS addresses it also",
    "reads AWS's public address-range file, without the access key.",
    "",
    "Regional sources are read in every region enabled for the account. A region that refuses the access key (a service control policy,",
    "for example) is skipped and shown as not readable on the Regions page: nothing there is checked or counted as passing.",
    "",
    "| Source | IAM actions | Checks that read it |",
    "|---|---|---|",
    ...awsRows,
    "",
  ].join("\n");
}

export const DOCS: Record<string, () => string> = { "docs/checks.md": checksDoc, "docs/permissions.md": permissionsDoc };

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  for (const [path, render] of Object.entries(DOCS)) {
    writeFileSync(new URL(`../${path}`, import.meta.url), render());
    console.log(`wrote ${path}`);
  }
}
